"""
    Роли пользователей
- Гость (Anonymous User)
Права:
Просмотр общедоступного контента
Ограниченный доступ к комментариям (например, без возможности оставлять, только читать)
Реклама или водяные знаки (для монетизации)
Зарегистрированный пользователь / Клиент (Registered Viewer)
Права:
Просмотр, лайк, дизлайк и сохранение в избранное
Возможность комментировать и подписываться на каналы
Получение рекомендаций и персонализированного контента
Доступ к плейлистам и истории просмотров
Контентмейкер / Создатель контента (Content Creator)
Права:
Загрузка и управление видео/контентом
Настройка канала, оформление и описание
Доступ к аналитике просмотров, комментариев и подписчиков
Монетизация (подключение рекламных возможностей, партнерские программы)
Возможность планировать премьеры или прямые трансляции
Верифицированный создатель / Партнёр (Verified Creator/Partner)
Права:
Все права обычного создателя, плюс:
Повышенная видимость на платформе (например, значок верификации)
Расширенная аналитика и дополнительные инструменты для монетизации
Приоритетная поддержка и дополнительные настройки (например, эксклюзивные функции)
Модератор (Moderator)
Права:
Управление комментариями: удаление, скрытие, модерация спорного контента
Просмотр и обработка жалоб от пользователей
Возможность временно ограничивать или блокировать контент, нарушающий правила платформы
Работа с инструментами для отслеживания нарушений и автоматизации модерации
Администратор (Administrator)
Права:
Полный доступ ко всем разделам платформы
Управление пользователями: назначение ролей, блокировки, восстановление аккаунтов
Настройка политики безопасности, конфигурация системы и контент-менеджмент
Работа с финансовыми операциями (в случае интеграции платежных систем)
Управление системными уведомлениями, аналитикой и отчетностью
Рекламодатель (Advertiser)
Права:
Доступ к рекламной платформе для размещения объявлений
Настройка таргетинга и бюджета рекламы
Аналитика эффективности рекламных кампаний
Возможность интеграции с внешними рекламными системами
Премиум-пользователь (Premium Subscriber)
Права:
Доступ к эксклюзивному или рекламно-чищенному контенту
Дополнительные функции, например, офлайн-доступ, улучшенное качество потоковой передачи
Возможность влиять на контент-политики (например, голосовать за нововведения)
Разработчик/Интегратор (Developer/Integrator)
Права:
Доступ к API платформы для интеграции внешних сервисов
Управление разработками, тестирование новых функций на стендах
Просмотр логов, аналитики и системных настроек (на уровне технического доступа)
"""
from rest_framework.permissions import IsAuthenticated

from rest_framework.permissions import BasePermission, IsAuthenticated

class IsUserRole(IsAuthenticated):
    role = None
    message = (
        ''
    )
    def has_permission(self, request, view):
        return super().has_permission(request, view) and request.user.user_role == self.role

    def has_object_permission(self, request, view, obj):
        return self.has_permission(request, view)

class IsClient(IsUserRole):
    role = 'CUS'
    message = (
        ''
    )

class IsModerator(IsUserRole):
    role = 'MOD'

class IsContentMaker(IsUserRole):
    role = 'CNM'

class IsDeveloper(IsUserRole):
    role = 'DEV'
